"""PyTorch reference for our CNN layers (Phase 9d): a small network with the same
layer kinds as tools/bc_train.py's encoder, its output and all gradients for one
batch, written to tests/data/torch_cnn.txt. tests_cpu checks the CPU reference
(temper/nn/reference_cpu.h) against it; tests_gpu checks the GPU layers too.

Network: Conv 3->4 k5 s2 p0 (-> 4 x 5 x 4), ReLU, Conv 4->5 k3 s2 p1 (-> 5 x 3 x 2), ReLU,
flatten (30), Linear -> 6,
LayerNorm(6). Input 2 x 3 x 13 x 11 (not square). Loss: sum(y * r), r fixed random,
so dL/dy = r.

    python tools/gen_torch_cnn_ref.py
"""
import os

import torch
import torch.nn as nn

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
torch.manual_seed(20261116)
torch.set_default_dtype(torch.float64)
net = nn.Sequential(nn.Conv2d(3, 4, 5, 2, 0), nn.ReLU(), nn.Conv2d(4, 5, 3, 2, 1), nn.ReLU(), nn.Flatten(),
                    nn.Linear(5 * 3 * 2, 6), nn.LayerNorm(6))
with torch.no_grad():  # LayerNorm's gamma and beta away from 1 and 0, so they are tested
    net[6].weight.uniform_(0.5, 1.5)
    net[6].bias.uniform_(-0.5, 0.5)
x = torch.randn(2, 3, 13, 11, requires_grad=True)
y = net(x)
r = torch.randn_like(y)
(y * r).sum().backward()


def line(name, t):
    return name + " " + " ".join(f"{v:.17g}" for v in t.detach().flatten().tolist())


out = ["# PyTorch " + torch.__version__ + " reference for the CNN layers. Generated by tools/gen_torch_cnn_ref.py.",
       line("x", x), line("conv1_w", net[0].weight), line("conv1_b", net[0].bias),
       line("conv2_w", net[2].weight), line("conv2_b", net[2].bias), line("fc_w", net[5].weight),
       line("fc_b", net[5].bias), line("ln_g", net[6].weight), line("ln_b", net[6].bias), line("dy", r),
       line("y", y), line("dx", x.grad), line("conv1_dw", net[0].weight.grad), line("conv1_db", net[0].bias.grad),
       line("conv2_dw", net[2].weight.grad), line("conv2_db", net[2].bias.grad), line("fc_dw", net[5].weight.grad),
       line("fc_db", net[5].bias.grad), line("ln_dg", net[6].weight.grad), line("ln_db", net[6].bias.grad)]
path = os.path.join(ROOT, "tests", "data", "torch_cnn.txt")
with open(path, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", os.path.relpath(path, ROOT))
